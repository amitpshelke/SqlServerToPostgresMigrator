using MigrationTool.Core.Interfaces;
using MigrationTool.Core.Models;
using Npgsql;

namespace MigrationTool.PostgreSql;

public sealed class PostgreSqlSchemaWriter : ISchemaWriter
{
    private readonly string _connectionString;

    public PostgreSqlSchemaWriter(string connectionString)
    {
        _connectionString = connectionString;
    }

    public async Task CreateSchemaAsync(IReadOnlyList<TableDefinition> tables, CancellationToken cancellationToken = default)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        try
        {
            foreach (var table in tables)
            {
                cancellationToken.ThrowIfCancellationRequested();
                await CreateSchemaIfNotExistsAsync(connection, transaction, table.SchemaName, cancellationToken);
                await CreateTableAsync(connection, transaction, table, cancellationToken);
            }

            await transaction.CommitAsync(cancellationToken);
        }
        catch
        {
            await transaction.RollbackAsync(cancellationToken);
            throw;
        }
    }

    private static async Task CreateSchemaIfNotExistsAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string schemaName, CancellationToken cancellationToken)
    {
        var sql = $"""CREATE SCHEMA IF NOT EXISTS {QuoteIdentifier(schemaName)};""";
        await ExecuteNonQueryAsync(connection, transaction, sql, cancellationToken);
    }

    public async Task CreateConstraintsAndIndexesAsync(
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken = default)
    {
        await using var connection =
            new NpgsqlConnection(_connectionString);

        await connection.OpenAsync(cancellationToken);

        await using var transaction =
            await connection.BeginTransactionAsync(cancellationToken);

        try
        {
            await CreatePrimaryKeysAsync(
                connection,
                transaction,
                tables,
                cancellationToken);

            await CreateUniqueConstraintsAsync(
                connection,
                transaction,
                tables,
                cancellationToken);

            await CreateCheckConstraintsAsync(
                connection,
                transaction,
                tables,
                cancellationToken);

            await CreateIndexesAsync(
                connection,
                transaction,
                tables,
                cancellationToken);

            await CreateForeignKeysAsync(
                connection,
                transaction,
                tables,
                cancellationToken);

            await transaction.CommitAsync(cancellationToken);
        }
        catch
        {
            await transaction.RollbackAsync(cancellationToken);
            throw;
        }
    }

    private static async Task CreateTableAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, TableDefinition table, CancellationToken cancellationToken) 
    {
        var columnDefinitions = table.Columns
                                     .OrderBy(c => c.OrdinalPosition)
                                     .Select(BuildColumnDefinition);

        var sql = $"""
            CREATE TABLE IF NOT EXISTS
                {QuoteIdentifier(table.SchemaName)}.{QuoteIdentifier(table.TableName)}
            (
                {string.Join(",\n    ", columnDefinitions)}
            );
            """;

        await ExecuteNonQueryAsync(connection, transaction, sql, cancellationToken);
    }

    private static string BuildColumnDefinition(ColumnDefinition column)
    {
        var definition = $"{QuoteIdentifier(column.Name)} {column.PostgreSqlDataType}";

        if (column.IsIdentity)
        {
            definition += " GENERATED BY DEFAULT AS IDENTITY";

            if (column.IdentitySeed.HasValue && column.IdentityIncrement.HasValue)
            {
                definition += $" (START WITH {column.IdentitySeed.Value} " +
                              $"INCREMENT BY {column.IdentityIncrement.Value})";
            }
        }

        if (!column.IsNullable)
        {
            definition += " NOT NULL";
        }

        if (!string.IsNullOrWhiteSpace(column.DefaultValue))
        {
            definition +=
                $" DEFAULT {ConvertDefaultValue(
                    column.DefaultValue,
                    column.PostgreSqlDataType)}";
        }

        return definition;
    }

    private static string ConvertDefaultValue(
    string defaultValue,
    string postgreSqlDataType)
    {
        var value = defaultValue.Trim();

        while (value.StartsWith('(') &&
               value.EndsWith(')'))
        {
            value = value[1..^1].Trim();
        }

        if (postgreSqlDataType.Equals(
                "BOOLEAN",
                StringComparison.OrdinalIgnoreCase))
        {
            return value switch
            {
                "1" => "TRUE",
                "0" => "FALSE",
                _ => value
            };
        }

        return value.ToLowerInvariant() switch
        {
            "getdate()" => "CURRENT_TIMESTAMP",
            "sysdatetime()" => "CURRENT_TIMESTAMP",
            "sysutcdatetime()" => "CURRENT_TIMESTAMP",
            "newid()" => "gen_random_uuid()",
            _ => value
        };
    }

    private static async Task ExecuteNonQueryAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string sql, CancellationToken cancellationToken)
    {
        Console.WriteLine(sql);
        Console.WriteLine("========================================");
        Console.WriteLine();

        await using var command = new NpgsqlCommand(sql, connection, transaction);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    private static string QuoteIdentifier(string identifier)
    {
        return "\"" + identifier.Replace("\"", "\"\"") + "\"";
    }

    private static async Task CreatePrimaryKeysAsync(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (table.PrimaryKey is null ||
                table.PrimaryKey.Columns.Count == 0)
            {
                continue;
            }

            var columns = string.Join(
                ", ",
                table.PrimaryKey.Columns.Select(QuoteIdentifier));

            var sql = $"""
            ALTER TABLE
                {QuoteIdentifier(table.SchemaName)}.
                {QuoteIdentifier(table.TableName)}
            ADD CONSTRAINT
                {QuoteIdentifier(table.PrimaryKey.Name)}
            PRIMARY KEY ({columns});
            """;

            await ExecuteNonQueryAsync(
                connection,
                transaction,
                sql,
                cancellationToken);
        }
    }

    private static async Task CreateUniqueConstraintsAsync(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            cancellationToken.ThrowIfCancellationRequested();

            foreach (var constraint in table.UniqueConstraints)
            {
                if (constraint.Columns.Count == 0)
                {
                    continue;
                }

                var columns = string.Join(
                    ", ",
                    constraint.Columns.Select(QuoteIdentifier));

                var sql = $"""
                ALTER TABLE
                    {QuoteIdentifier(table.SchemaName)}.
                    {QuoteIdentifier(table.TableName)}
                ADD CONSTRAINT
                    {QuoteIdentifier(constraint.Name)}
                UNIQUE ({columns});
                """;

                await ExecuteNonQueryAsync(
                    connection,
                    transaction,
                    sql,
                    cancellationToken);
            }
        }
    }

    private static async Task CreateCheckConstraintsAsync(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            cancellationToken.ThrowIfCancellationRequested();

            foreach (var constraint in table.CheckConstraints)
            {
                if (string.IsNullOrWhiteSpace(constraint.Definition))
                {
                    continue;
                }

                var sql = $"""
                ALTER TABLE
                    {QuoteIdentifier(table.SchemaName)}.
                    {QuoteIdentifier(table.TableName)}
                ADD CONSTRAINT
                    {QuoteIdentifier(constraint.Name)}
                CHECK {constraint.Definition};
                """;

                await ExecuteNonQueryAsync(
                    connection,
                    transaction,
                    sql,
                    cancellationToken);
            }
        }
    }

    private static async Task CreateIndexesAsync(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            cancellationToken.ThrowIfCancellationRequested();

            foreach (var index in table.Indexes)
            {
                if (index.IsPrimaryKey ||
                    index.IsUniqueConstraint ||
                    index.IsDisabled ||
                    index.Columns.Count == 0)
                {
                    continue;
                }

                var columns = string.Join(
                    ", ",
                    index.Columns.Select(QuoteIdentifier));

                var uniqueKeyword =
                    index.IsUnique ? "UNIQUE " : string.Empty;

                var sql = $"""
                CREATE {uniqueKeyword}INDEX
                    {QuoteIdentifier(index.Name)}
                ON
                    {QuoteIdentifier(table.SchemaName)}.
                    {QuoteIdentifier(table.TableName)}
                ({columns})
                """;

                if (index.IncludedColumns.Count > 0)
                {
                    sql += $"""
                    
                    INCLUDE (
                        {string.Join(
                                ", ",
                                index.IncludedColumns.Select(QuoteIdentifier))}
                    )
                    """;
                }

                if (!string.IsNullOrWhiteSpace(index.FilterDefinition))
                {
                    sql += $"""
                    
                    WHERE {index.FilterDefinition}
                    """;
                }

                sql += ";";

                await ExecuteNonQueryAsync(
                    connection,
                    transaction,
                    sql,
                    cancellationToken);
            }
        }
    }

    private static async Task CreateForeignKeysAsync(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    IReadOnlyList<TableDefinition> tables,
    CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            cancellationToken.ThrowIfCancellationRequested();

            foreach (var foreignKey in table.ForeignKeys)
            {
                if (foreignKey.Columns.Count == 0 ||
                    foreignKey.ReferencedColumns.Count == 0)
                {
                    continue;
                }

                var columns = string.Join(
                    ", ",
                    foreignKey.Columns.Select(QuoteIdentifier));

                var referencedColumns = string.Join(
                    ", ",
                    foreignKey.ReferencedColumns.Select(QuoteIdentifier));

                var sql = $"""
                ALTER TABLE
                    {QuoteIdentifier(table.SchemaName)}.
                    {QuoteIdentifier(table.TableName)}
                ADD CONSTRAINT
                    {QuoteIdentifier(foreignKey.Name)}
                FOREIGN KEY ({columns})
                REFERENCES
                    {QuoteIdentifier(foreignKey.ReferencedSchema)}.
                    {QuoteIdentifier(foreignKey.ReferencedTable)}
                    ({referencedColumns})
                """;

                var deleteAction =
                    ConvertReferentialAction(
                        foreignKey.DeleteAction);

                var updateAction =
                    ConvertReferentialAction(
                        foreignKey.UpdateAction);

                if (!string.IsNullOrWhiteSpace(deleteAction))
                {
                    sql += $" ON DELETE {deleteAction}";
                }

                if (!string.IsNullOrWhiteSpace(updateAction))
                {
                    sql += $" ON UPDATE {updateAction}";
                }

                sql += ";";

                await ExecuteNonQueryAsync(
                    connection,
                    transaction,
                    sql,
                    cancellationToken);
            }
        }
    }

    private static string ConvertReferentialAction(
    string action)
    {
        return action.ToUpperInvariant() switch
        {
            "NO_ACTION" => "NO ACTION",
            "CASCADE" => "CASCADE",
            "SET_NULL" => "SET NULL",
            "SET_DEFAULT" => "SET DEFAULT",
            _ => "NO ACTION"
        };
    }
}