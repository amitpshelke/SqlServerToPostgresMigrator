using System.Text;
using MigrationTool.Core.Interfaces;
using MigrationTool.Core.Models;

namespace MigrationTool.PostgreSql;

public sealed class PostgreSqlSchemaGenerator : ISchemaGenerator
{
    private readonly ITypeMapper _typeMapper;

    public PostgreSqlSchemaGenerator(ITypeMapper typeMapper)
    {
        _typeMapper = typeMapper;
    }

    public string GenerateCreateTableScript(
        TableDefinition table)
    {
        var builder = new StringBuilder();

        builder.AppendLine(
            $"CREATE SCHEMA IF NOT EXISTS {QuoteIdentifier(table.SchemaName)};");

        builder.AppendLine();

        builder.AppendLine(
            $"CREATE TABLE IF NOT EXISTS " +
            $"{QuoteIdentifier(table.SchemaName)}." +
            $"{QuoteIdentifier(table.TableName)}");

        builder.AppendLine("(");

        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];

            column.PostgreSqlDataType =
                _typeMapper.MapType(
                    column.SqlServerDataType,
                    column.MaxLength,
                    column.Precision,
                    column.Scale);

            var definition = new StringBuilder();

            definition.Append("    ");
            definition.Append(QuoteIdentifier(column.Name));
            definition.Append(' ');
            definition.Append(column.PostgreSqlDataType);

            if (column.IsIdentity)
            {
                definition.Append(
                    " GENERATED BY DEFAULT AS IDENTITY");
            }

            if (!column.IsNullable)
            {
                definition.Append(" NOT NULL");
            }

            if (column.DefaultValue is not null)
            {
                definition.Append(" DEFAULT ");
                definition.Append(
                    ConvertDefaultValue(
                        column.DefaultValue.ToString()!));
            }

            if (i < table.Columns.Count - 1)
            {
                definition.Append(',');
            }

            builder.AppendLine(definition.ToString());
        }

        builder.AppendLine(");");
        builder.AppendLine();

        return builder.ToString();
    }

    private static string QuoteIdentifier(string identifier)
    {
        return "\"" +
               identifier.Replace("\"", "\"\"") +
               "\"";
    }

    private static string ConvertDefaultValue(string value)
    {
        var result = value.Trim();

        if (result.Equals("(getdate())",
                StringComparison.OrdinalIgnoreCase))
        {
            return "CURRENT_TIMESTAMP";
        }

        if (result.Equals("(sysdatetime())",
                StringComparison.OrdinalIgnoreCase))
        {
            return "CURRENT_TIMESTAMP";
        }

        if (result.Equals("(newid())",
                StringComparison.OrdinalIgnoreCase))
        {
            return "gen_random_uuid()";
        }

        return result.Trim('(', ')');
    }
}